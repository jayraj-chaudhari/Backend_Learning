//          API vs SSR
//API - Application Programming Interface
//            SSR - Server Side Rendering
//API - sends data to the client, client renders the data
//            SSR - sends fully rendered HTML to the client, client just displays it
//API - JS framework (React, Vue, Angular) is used to render the data on the client side
//            SSR - JS framework (React, Vue, Angular) is used to render the data on the server side
//API - client side routing is used to navigate between pages
//            SSR - server side routing is used to navigate between pages
//API - JSON is used to send data from the server to the client
//            SSR - HTML is used to send data from the server to the client
